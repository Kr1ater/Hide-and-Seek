// Общие типы игры. Вынесены отдельно, чтобы на них могли ссылаться
// и менеджеры, и компоненты игрока, не зная друг о друге.

public enum GameRole
{
    // Роль ещё не назначена: игрок выглядит охотником и смотрит от третьего лица.
    // Это полноценное состояние, а не "нет данных".
    None,
    Hider,
    Hunter
}

public enum GamePhase
{
    // Сцена загружена не у всех - ждём отставших
    WaitingForPlayers,
    // Короткий отсчёт "игра начнётся через 5 4 3"
    Countdown,
    // Все бегают по карте и изучают её, роли ещё не розданы
    Preparation,
    // Отсчёт перед объявлением ролей
    RoleReveal,
    // Роли розданы: прячущиеся прячутся, охотник заперт на месте
    HunterLocked,
    // Охотник выпущен, идёт основной таймер
    Hunt,
    // Раунд закончен, показываем экран итога
    RoundOver
}

public enum RoundOutcome
{
    None,
    // Охотник нашёл всех
    HunterWon,
    // Время вышло
    HidersWon
}
